function ResourceFormPage() {
  const [, setLocation] = useLocation(); const create = useCreateResource(); const qc = useQueryClient(); const [form, setForm] = useState({ name: '', category: 'food' as typeof categories[number], description: '', quantity: '', unit: 'boxes', location: '', expiryDate: '' });
  const set = (key: keyof typeof form, value: string) => setForm((prev) => ({ ...prev, [key]: value }));
  const submit = (e: React.FormEvent) => { e.preventDefault(); create.mutate({ data: { ...form, quantity: Number(form.quantity), expiryDate: form.expiryDate || null } }, { onSuccess: () => { qc.invalidateQueries({ queryKey: getListResourcesQueryKey() }); qc.invalidateQueries({ queryKey: getGetDashboardQueryKey() }); setLocation('/resources'); } }); };
  return <div className="mx-auto max-w-3xl"><SectionTitle eyebrow="New listing" title="Put surplus in motion" description="Give another team enough context to make a confident request."/><form onSubmit={submit} className="space-y-6 rounded-xl border border-card-border bg-card p-5 sm:p-7"><div className="grid gap-5 sm:grid-cols-2"><Field label="Resource name"><FormInput required value={form.name} onChange={(v) => set('name', v)} placeholder="e.g. Shelf-stable lentil meals"/></Field><Field label="Category"><select value={form.category} onChange={(e) => set('category', e.target.value)} data-testid="select-new-resource-category">{categories.map((c) => <option key={c} value={c}>{categoryLabel(c)}</option>)}</select></Field></div><Field label="Description"><textarea value={form.description} onChange={(e) => set('description', e.target.value)} placeholder="What should a receiving team know about condition, packing, or use?" rows={4} data-testid="textarea-resource-description"/></Field><div className="grid gap-5 sm:grid-cols-3"><Field label="Quantity"><FormInput required type="number" value={form.quantity} onChange={(v) => set('quantity', v)} placeholder="240"/></Field><Field label="Unit"><FormInput required value={form.unit} onChange={(v) => set('unit', v)} placeholder="boxes"/></Field><Field label="Available in"><FormInput required value={form.location} onChange={(v) => set('location', v)} placeholder="Oakland, CA"/></Field></div><Field label="Best before (optional)"><FormInput type="date" value={form.expiryDate} onChange={(v) => set('expiryDate', v)}/></Field>{create.isError && <InlineError message="This listing could not be saved. Please check the details."/>}<div className="flex flex-col-reverse gap-3 border-t border-border pt-5 sm:flex-row sm:justify-end"><Button type="button" variant="quiet" onClick={() => setLocation('/resources')} data-testid="button-cancel-resource">Cancel</Button><Button type="submit" disabled={create.isPending} data-testid="button-submit-resource">{create.isPending ? 'Saving listingâ€¦' : 'Publish resource'}<ArrowRight size={16}/></Button></div></form></div>;
}

export default ResourceFormPage;

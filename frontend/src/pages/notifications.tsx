function NotificationsPage() {
  const notifications = useListNotifications(undefined, { query: { queryKey: getListNotificationsQueryKey() } }); const read = useMarkNotificationRead(); const qc = useQueryClient();
  return <><SectionTitle eyebrow="Updates" title="Notifications" description="A simple record of what changed in your coordination workspace." action={<Button variant="outline" onClick={() => notifications.data?.filter((n) => !n.read).forEach((n) => read.mutate({ id: n.id }, { onSuccess: () => qc.invalidateQueries({ queryKey: getListNotificationsQueryKey() }) }))} data-testid="button-mark-all-read"><Check size={15}/> Mark all read</Button>}/>{notifications.isLoading ? <SkeletonList rows={5}/> : notifications.isError ? <ErrorState retry={() => notifications.refetch()}/> : !notifications.data?.length ? <EmptyState icon={Bell} title="All quiet here" description="Updates about requests, transfers, and system activity will appear here."/> : <div className="space-y-2">{notifications.data.map((notification) => <button key={notification.id} onClick={() => !notification.read && read.mutate({ id: notification.id }, { onSuccess: () => qc.invalidateQueries({ queryKey: getListNotificationsQueryKey() }) })} className={`flex w-full items-start gap-4 rounded-xl border p-4 text-left ${notification.read ? 'border-card-border bg-card' : 'border-primary/25 bg-secondary/35'}`} data-testid={`notification-${notification.id}`}><div className={`mt-0.5 flex size-9 shrink-0 items-center justify-center rounded-lg ${notification.read ? 'bg-muted text-muted-foreground' : 'bg-primary text-primary-foreground'}`}><Bell size={16}/></div><div className="min-w-0 flex-1"><div className="flex flex-wrap items-center gap-2"><h3 className="text-sm font-bold">{notification.title}</h3>{!notification.read && <span className="size-1.5 rounded-full bg-accent"/>}</div><p className="mt-1 text-sm text-muted-foreground">{notification.message}</p><div className="mt-2 font-mono text-[10px] uppercase tracking-wider text-muted-foreground">{formatDate(notification.createdAt)} Â· {humanStatus(notification.type)}</div></div></button>)}</div>}</>;
}


function RequestFormPage() {
  const [, setLocation] = useLocation(); const create = useCreateRequest(); const qc = useQueryClient(); const [form, setForm] = useState({ resourceType: '', category: 'food' as typeof categories[number], quantity: '', urgency: 'medium' as 'low' | 'medium' | 'high' | 'critical', location: '', requiredDate: '' });
  const set = (key: keyof typeof form, value: string) => setForm((prev) => ({ ...prev, [key]: value }));
  return <div className="mx-auto max-w-3xl"><SectionTitle eyebrow="New request" title="Name what is needed" description="Specific requests help the network respond with less back-and-forth."/><form onSubmit={(e) => { e.preventDefault(); create.mutate({ data: { ...form, quantity: Number(form.quantity) } }, { onSuccess: () => { qc.invalidateQueries({ queryKey: getListRequestsQueryKey() }); qc.invalidateQueries({ queryKey: getGetDashboardQueryKey() }); setLocation('/requests'); } }); }} className="space-y-6 rounded-xl border border-card-border bg-card p-5 sm:p-7"><div className="grid gap-5 sm:grid-cols-2"><Field label="What do you need?"><FormInput required value={form.resourceType} onChange={(v) => set('resourceType', v)} placeholder="e.g. Pediatric antibiotics"/></Field><Field label="Category"><select value={form.category} onChange={(e) => set('category', e.target.value)} data-testid="select-request-category">{categories.map((c) => <option key={c} value={c}>{categoryLabel(c)}</option>)}</select></Field></div><div className="grid gap-5 sm:grid-cols-2"><Field label="Quantity"><FormInput required type="number" value={form.quantity} onChange={(v) => set('quantity', v)} placeholder="120"/></Field><Field label="Urgency"><select value={form.urgency} onChange={(e) => set('urgency', e.target.value)} data-testid="select-request-urgency">{['low', 'medium', 'high', 'critical'].map((u) => <option key={u} value={u}>{u}</option>)}</select></Field></div><div className="grid gap-5 sm:grid-cols-2"><Field label="Delivery location"><FormInput required value={form.location} onChange={(v) => set('location', v)} placeholder="Fresno, CA"/></Field><Field label="Needed by"><FormInput required type="date" value={form.requiredDate} onChange={(v) => set('requiredDate', v)}/></Field></div>{create.isError && <InlineError message="This request could not be created. Please check the details."/>}<div className="flex flex-col-reverse gap-3 border-t border-border pt-5 sm:flex-row sm:justify-end"><Button type="button" variant="quiet" onClick={() => setLocation('/requests')} data-testid="button-cancel-request">Cancel</Button><Button type="submit" disabled={create.isPending} data-testid="button-submit-request">{create.isPending ? 'Sending requestâ€¦' : 'Send request'}<ArrowRight size={16}/></Button></div></form></div>;
}

